"""
Генератор синтетических XLSX-фикстур для тестов.

Создаёт детерминированный XLSX с двумя листами («Сборочные задания» и «КИЗ»)
и 10 заголовками согласно доказанной структуре Wildberries.

Содержит:
- Продажа, Возврат, -
- Пустые чек/ФН
- Целая и дробная стоимость
- 3 разных валидных КИ-31 (чистый, FFFD-хвост, GS-текст), повреждённый, дубликат
- Все строки без реальных данных ЧЗ
"""

import os
import tempfile
from typing import Any

try:
    import openpyxl
    from openpyxl import Workbook
except ImportError:
    openpyxl = None  # type: ignore[assignment]
    Workbook = None  # type: ignore[assignment]

# ── Константы ────────────────────────────────────────────────────────────────

HEADERS = [
    "№ задания",
    "Стикер",
    "КИЗ",
    "Номер чека",
    "Стоимость",
    "Валюта",
    "Номер фискального накопителя",
    "Дата",
    "Тип операции",
    "Признак продажи юрлицу",
]

# Валидные КИ-31 (разные — чтобы строки 1/2/3 не были дублями)
KI_CLEAN = "010123456789012321SERIAL1234567"
KI_CLEAN2 = "010123456789099921GOODS9876543X"
KI_CLEAN3 = "010123456789011121PRODCT5555555"

# КИ + U+FFFD + 91(4) + U+FFFD + 92(44) — WB-вариант (openpyxl не принимает \u001d)
FFFD_CHAR = "\ufffd"
KI_WITH_FFFD = (
    KI_CLEAN2
    + FFFD_CHAR
    + "91abcd"
    + FFFD_CHAR
    + "92"
    + "B" * 44
)

# КИ + GS (текстовый литерал) + 91(4) + GS + 92(44) — для тестов текстового GS
KI_WITH_GS_TEXT = (
    KI_CLEAN3
    + "GS"
    + "91abcd"
    + "GS"
    + "92"
    + "B" * 44
)

# Повреждённый КИ (невалидный префикс)
KI_CORRUPTED = "020123456789012321SERIAL1234567"

# Другой валидный КИ для дубликата
KI_DUP = "014612345678901221ABC123XYZ7890"


def create_synthetic_xlsx(path: str | None = None) -> str:
    """
    Создаёт детерминированный XLSX-файл.

    Args:
        path: Путь для сохранения. Если None — временный файл.

    Returns:
        Путь к созданному файлу.
    """
    if openpyxl is None:
        raise RuntimeError("openpyxl не установлен")

    if path is None:
        fd, path = tempfile.mkstemp(suffix=".xlsx")
        os.close(fd)

    wb = Workbook()

    # ── Лист 1: Сборочные задания ──────────────────────────────────────────
    ws1 = wb.active
    ws1.title = "Сборочные задания"
    ws1.append(["№", "Артикул", "Количество"])
    ws1.append(["1", "ART-001", "5"])
    ws1.append(["2", "ART-002", "3"])

    # ── Лист 2: КИЗ ────────────────────────────────────────────────────────
    ws2 = wb.create_sheet(title="КИЗ")
    ws2.append(HEADERS)

    rows: list[list[Any]] = [
        # 1. Продажа с чистым КИ-31, целая стоимость
        [1, "STK-001", KI_CLEAN, "CHK-001", 1500, "RUB",
         "FN-001", "2026-09-01", "Продажа", "-"],
        # 2. Продажа с U+FFFD-разделителем (WB-стиль), дробная стоимость
        [2, "STK-002", KI_WITH_FFFD, "CHK-002", 1299.99, "RUB",
         "FN-002", "2026-09-01", "Продажа", "-"],
        # 3. Продажа с текстовым GS
        [3, "STK-003", KI_WITH_GS_TEXT, "CHK-003", 2500.50, "RUB",
         "FN-003", "2026-09-02", "Продажа", "-"],
        # 4. Возврат (должен фильтроваться)
        [4, "STK-004", KI_CLEAN, "CHK-004", 1500, "RUB",
         "FN-004", "2026-09-01", "Возврат", "-"],
        # 5. "-" (должен фильтроваться)
        [5, "STK-005", KI_CLEAN, "CHK-005", 3000, "RUB",
         "FN-005", "2026-09-01", "-", "-"],
        # 6. Продажа без чека (пустой чек)
        [6, "STK-006", KI_CLEAN, "", 2000, "RUB",
         "FN-006", "2026-09-01", "Продажа", "-"],
        # 7. Продажа без ФН (пустой ФН)
        [7, "STK-007", KI_CLEAN, "CHK-007", 1800, "RUB",
         "", "2026-09-01", "Продажа", "-"],
        # 8. Повреждённый КИ (невалидный)
        [8, "STK-008", KI_CORRUPTED, "CHK-008", 999, "RUB",
         "FN-008", "2026-09-02", "Продажа", "-"],
        # 9. Дубликат строки 1
        [9, "STK-001", KI_CLEAN, "CHK-001", 1500, "RUB",
         "FN-001", "2026-09-01", "Продажа", "-"],
        # 10. Продажа, целая стоимость, все поля
        [10, "STK-010", KI_DUP, "CHK-010", 4500, "RUB",
         "FN-010", "2026-09-02", "Продажа", "-"],
    ]

    for row in rows:
        ws2.append(row)

    wb.save(path)
    return path


def get_expected_stats() -> dict:
    """Возвращает ожидаемую статистику для синтетического файла."""
    return {
        "total_rows": 10,
        "sale_rows": 7,       # строки 1,2,3,6,7,8,10 (исключая Возврат и -)
        "return_rows": 1,     # строка 4
        "dash_rows": 1,       # строка 5
        "empty_check": 1,     # строка 6
        "empty_fn": 1,        # строка 7
        "corrupted_kiz": 1,   # строка 8
        "duplicate": 1,       # строка 9 — дубль строки 1
        "valid_sales": 4,     # 1,2,3,10 (чистые продажи с чеком+ФН и валидным КИ)
    }
